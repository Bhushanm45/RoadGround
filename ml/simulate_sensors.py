    parser.add_argument("--rides", type=int, default=10, help="Number of distinct rides to simulate")
    parser.add_argument("--windows", type=int, default=60, help="Windows per ride (1 sec each)")
    parser.add_argument("--url", type=str, default="http://127.0.0.1:5000/api/telemetry",
                        help="Backend URL for live streaming")
    parser.add_argument("--route", type=str, default="FC_ROAD", choices=list(PUNE_ROUTES.keys()),
                        help="Pune route for live telemetry")
    parser.add_argument("--duration", type=int, default=30, help="Live stream duration in seconds")

    args = parser.parse_args()

    if args.mode == "generate_dataset":
        generate_synthetic_dataset(args.output, n_rides=args.rides, windows_per_ride=args.windows)
    elif args.mode == "stream_live":
        stream_live_telemetry_to_backend(backend_url=args.url, route_key=args.route, duration_seconds=args.duration)
