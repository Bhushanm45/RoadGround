"""
RoadGuard AI - Sensor & Route Simulator
========================================
Generates physics-based synthetic sensor data and simulated GPS routes for:
1. Generating offline labeled datasets for ML training and validation.
2. Streaming live mock telemetry over HTTP to the Flask backend for live demo and testing.

NOTE: All data generated by this module is explicitly labeled as SYNTHETIC.
Never present synthetic data as real physical measurements.

Waveform Physics & Profiles (Derived from Road Vibration Research):
- NORMAL_ROAD: Stable 1.0g baseline, low variance (sigma ~ 0.03g), smooth engine hum.
- POTHOLE: Sharp cavity drop (-1.2g to -1.6g), immediate high-energy rebound shock (+2.0g to +3.5g),
           damped ringing (~35-45 Hz), duration 150-250 ms, high kurtosis.
- SPEED_BREAKER: Smooth half-sine elevation curve (+0.8g to +1.2g), duration 600-900 ms,
                 low frequency (~1.5 Hz), low kurtosis.
- ROUGH_ROAD: Continuous stochastic high-frequency chatter (±0.4g spread), elevated variance
              without a single isolated shock.
"""

